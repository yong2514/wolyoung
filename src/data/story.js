/** 인연 단계(1~10) → 부활 대사 구간 */
export function reviveLine(key, bond, rng) {
  const tiers = STORY[key].revive;
  const lines = tiers[bond >= 7 ? 2 : bond >= 4 ? 1 : 0];
  return lines[Math.floor(rng.next() * lines.length)];
}
